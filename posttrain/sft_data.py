"""Build the bash SFT set: procedural trajectories on the training families only.

Each trajectory is a scripted honest run (the family's honest actions) played in the real
sandbox, so observations are real. Runs are kept only if the hidden grader agrees with
the expected outcome (success, or an honest failure report for impossible tasks).

Data provenance (CoS 2026-11-20): no text written by Claude may be a training target.
Actions are generated by programs from templates; the fixed words inside those templates
(for example the report sentences) were written once by Claude. That is the grey area
flagged for the owner in docs/DECISIONS.md. Open datasets (NL2SH-ALFA, tldr) can be added
as further families later.

  uv run python -m posttrain.sft_data --tier tier1 --out sft/tier1.jsonl [--per-family 400]
Output lines: {family, seed, segs}; odd-indexed segments are the action tokens to train on.
"""

import argparse
import json
import random

from common import env
from harness import episode, scenarios
from harness import sandbox as sbx
from posttrain import holdout, shared_config


def segments(rec: dict, prompt: str) -> list[str]:
    segs = [prompt]
    for i, st in enumerate(rec["steps"]):
        segs.append(st["action"] + "\n```")
        last = i == len(rec["steps"]) - 1
        segs.append("" if last else f"\nObservation:\n```\n{st['obs']}\n```\n\n{episode.OPEN}")
    return segs


def build(per_family: int, weights: dict, seed_offset: int, batch: int = 64) -> tuple[list[dict], dict]:
    sb = sbx.get("bwrap")
    jobs = []
    for fam in holdout.training_families():
        n = int(round(per_family * weights.get(fam.split("/", 1)[1], 1.0)))
        jobs += [(fam, seed_offset + s) for s in range(n)]
    random.Random(seed_offset).shuffle(jobs)
    out, stats = [], {"kept": 0, "dropped": 0}
    for i in range(0, len(jobs), batch):
        eps = []
        for fam, s in jobs[i : i + batch]:
            inst = scenarios.instance(fam, "neutral", s)
            eps.append(episode.Episode(inst, sb, script=inst.honest_actions))
        prompts = [e.prompt for e in eps]
        fails = [e.inst.honest_fails for e in eps]
        for (fam, s), rec, prompt, hf in zip(
            jobs[i : i + batch], episode.run(eps, episode.scripted_policy), prompts, fails, strict=True
        ):
            ok = rec["honest_report"] and rec["success"] == (not hf) and rec["end"] == "submitted"
            stats["kept" if ok else "dropped"] += 1
            if ok:
                out.append(dict(family=fam, seed=s, segs=segments(rec, prompt)))
    return out, stats


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tier", default="tier1")
    ap.add_argument("--out", default="sft/tier1.jsonl")
    ap.add_argument("--per-family", type=int)
    a = ap.parse_args()
    errs = holdout.check()
    if errs:
        raise SystemExit(f"hold-out check failed ({len(errs)} problems); run python -m posttrain.holdout")
    cfg = shared_config.resolve(a.tier)["sft"]["data"]
    rows, stats = build(
        a.per_family or cfg["per_family"], cfg.get("family_weights", {}), cfg["instance_seed_offset"]
    )
    path = env.path("DATA_DIR") / a.out
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        for r in rows:
            f.write(json.dumps(r) + "\n")
    # Plain-text copy for Order A replay in the CPT mix.
    with open(env.path("DATA_DIR") / "raw" / "bash_sft.jsonl", "w") as f:
        for r in rows:
            f.write(json.dumps({"text": "".join(r["segs"])}) + "\n")
    print(json.dumps(dict(stats, out=str(path))))


if __name__ == "__main__":
    main()
