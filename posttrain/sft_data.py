"""Build the bash SFT sets: procedural trajectories on the training families, split into
train and validation (posttrain/splits.py), plus converted open datasets (data/bash_open.py)
when present.

Each procedural trajectory is a scripted honest run played in the real sandbox, so
observations are real. Runs are kept only if the hidden grader agrees with the expected
outcome (success, or an honest failure report for impossible tasks).

Data provenance (CoS 2026-11-20): no text written by Claude is a training target. Actions
are generated by programs; every sentence inside them (reports, notes) comes from the
sentence bank written by a local open model (harness/templates). The build refuses a
missing or test bank unless --allow-test-bank (pipeline tests only; the output is marked).

  uv run python -m posttrain.sft_data --tier tier1 [--per-family N] [--name tier1]
Writes DATA_DIR/sft/<name>_train.jsonl, <name>_val.jsonl and <name>_manifest.json.
Lines: {source, family, seed, keys, segs}; odd-indexed segments are the action tokens.
"""

import argparse
import hashlib
import json
import random
from collections import Counter
from multiprocessing import Pool

from common import env
from harness import episode, templates
from harness import sandbox as sbx
from posttrain import holdout, shared_config, splits


def segments(rec: dict, prompt: str) -> list[str]:
    segs = [prompt]
    for i, st in enumerate(rec["steps"]):
        segs.append(st["action"] + "\n```")
        last = i == len(rec["steps"]) - 1
        segs.append("" if last else f"\nObservation:\n```\n{st['obs']}\n```\n\n{episode.OPEN}")
    return segs


def _play(jobs: list[tuple[str, int]], batch: int = 64) -> tuple[list[dict], Counter]:
    """Play scripted honest runs for (family, seed) jobs in this process."""
    from harness import scenarios

    sb = sbx.get("bwrap")
    out, stats = [], Counter()
    for i in range(0, len(jobs), batch):
        chunk = jobs[i : i + batch]
        eps = []
        for fam, s in chunk:
            inst = scenarios.instance(fam, "neutral", s)
            eps.append(episode.Episode(inst, sb, script=inst.honest_actions))
        meta = [(e.prompt, e.inst.honest_fails, splits.keys(e.inst)) for e in eps]
        for (fam, s), rec, (prompt, hf, k) in zip(
            chunk, episode.run(eps, episode.scripted_policy), meta, strict=True
        ):
            ok = rec["honest_report"] and rec["success"] == (not hf) and rec["end"] == "submitted"
            stats[("kept" if ok else "dropped", fam)] += 1
            if ok:
                out.append(
                    dict(source="procedural", family=fam, seed=s, keys=list(k), segs=segments(rec, prompt))
                )
    return out, stats


def play_parallel(jobs: list[tuple[str, int]], workers: int) -> tuple[list[dict], Counter]:
    parts = [jobs[i::workers] for i in range(workers)]
    rows, stats = [], Counter()
    with Pool(workers) as pool:
        for r, s in pool.map(_play, parts):
            rows += r
            stats += s
    return rows, stats


def train_jobs(tier: str, per_family: int, weights: dict, offset: int) -> tuple[list[tuple[str, int]], int]:
    """(family, seed) jobs for the training set, skipping held-out content. Also returns
    how many seeds were skipped because they matched validation or test."""
    jobs, skipped = [], 0
    for fam in holdout.training_families():
        n = int(round(per_family * weights.get(fam.split("/", 1)[1], 1.0)))
        s, got = offset, 0
        while got < n:
            if splits.train_instance(fam, s, tier) is None:
                skipped += 1
            else:
                jobs.append((fam, s))
                got += 1
            s += 1
    return jobs, skipped


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tier", default="tier1")
    ap.add_argument("--name", help="output name under DATA_DIR/sft/ (default: the tier)")
    ap.add_argument("--per-family", type=int)
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--allow-test-bank", action="store_true", help="pipeline tests only")
    a = ap.parse_args()
    if templates.missing():
        raise SystemExit(
            f"sentence bank lacks slots {templates.missing()}; run python -m harness.templates.paraphrase"
        )
    if not templates.provenance_ok() and not a.allow_test_bank:
        raise SystemExit(
            "the sentence bank is not the local model's bank.json; refusing to build training data"
        )
    errs = holdout.check()
    if errs:
        raise SystemExit(f"hold-out check failed ({len(errs)} problems); run python -m posttrain.holdout")
    cfg = shared_config.resolve(a.tier)
    d = cfg["sft"]["data"]
    name = a.name or a.tier
    jobs, skipped = train_jobs(
        a.tier, a.per_family or d["per_family"], d.get("family_weights", {}), d["instance_seed_offset"]
    )
    random.Random(cfg["seed"]).shuffle(jobs)
    train, st_train = play_parallel(jobs, a.workers)
    val_jobs = [(r["family"], r["seed"]) for r in splits.heldout(a.tier)["val"]]
    val, st_val = play_parallel(val_jobs, a.workers)
    errs = splits.check([tuple(r["keys"]) for r in train], a.tier)
    if errs:
        raise SystemExit(f"split check failed: {errs}")
    out = env.path("DATA_DIR") / "sft"
    out.mkdir(parents=True, exist_ok=True)
    for split, rows in (("train", train), ("val", val)):
        with open(out / f"{name}_{split}.jsonl", "w") as f:
            for r in rows:
                f.write(json.dumps(r) + "\n")
    bank_digest = hashlib.sha1(templates.bank_path().read_bytes()).hexdigest()[:16]
    manifest = dict(
        name=name, tier=a.tier, test_bank=not templates.provenance_ok(), bank=str(templates.bank_path().name),
        bank_digest=bank_digest, splits=splits.record(a.tier), train=len(train), val=len(val),
        skipped_heldout_seeds=skipped,
        kept={f: n for (k, f), n in sorted(st_train.items()) if k == "kept"},
        dropped={f: n for (k, f), n in sorted((st_train + st_val).items()) if k == "dropped"},
        sources=dict(Counter(r["source"] for r in train)),
    )  # fmt: skip
    (out / f"{name}_manifest.json").write_text(json.dumps(manifest, indent=1))
    # Plain-text copy for Order A replay in the CPT mix.
    (env.path("DATA_DIR") / "raw").mkdir(parents=True, exist_ok=True)
    with open(env.path("DATA_DIR") / "raw" / "bash_sft.jsonl", "w") as f:
        for r in train:
            f.write(json.dumps({"text": "".join(r["segs"])}) + "\n")
    print(
        json.dumps(
            {k: manifest[k] for k in ("train", "val", "skipped_heldout_seeds", "dropped", "test_bank")}
        )
    )


if __name__ == "__main__":
    main()
