"""Build markdown tables from ../results/{oneliner,agent}_raw.jsonl -> ../results/tables.md"""
import json, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(os.path.dirname(HERE), "results")


def load(name):
    p = os.path.join(RES, name)
    return [json.loads(l) for l in open(p)] if os.path.exists(p) else []


def ci(p, n):
    """95% Wilson interval half-width, in points."""
    if n == 0:
        return 0
    z = 1.96
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (c - h, c + h)


one = {r["label"]: r for r in load("oneliner_raw.jsonl")}
ag = load("agent_raw.jsonl")
base = {r["label"]: r for r in ag if r.get("variant", "base") == "base"}
out = ["# Measured tables (generated by scripts/summarize.py)\n"]

out.append("## Main table: one-liners and multi-step pilot (variant: base harness, 2-shot)\n")
out.append("One-liners: 20 tasks, greedy, graded by execution. Pilot: 8 tasks x k samples, T=0.6, max 10 steps; "
           "success = hidden grader passes; pass@k = share of tasks solved at least once.\n")
out.append("| Model | Bash 1-liner /20 | Python 1-liner /20 | Pilot bash | Pilot Python | Pilot JSON tools | best pass@k | mean of 3 |")
out.append("|:-|-:|-:|-:|-:|-:|-:|-:|")
rows = []
for lab, r in base.items():
    s = r["summary"]
    o = one.get(lab, {})
    m = sum(s[i]["success"] for i in ("bash", "python", "tools") if i in s) / 3
    best_pk = max(s[i]["pass_at_k"] for i in s)
    rows.append((m, lab, o.get("bash", "."), o.get("python", "."), s, best_pk))
for m, lab, ob, op, s, pk in sorted(rows, key=lambda x: -x[0]):
    f = lambda i: f"{s[i]['success']:.2f}" if i in s else "."
    out.append(f"| {lab} | {ob} | {op} | {f('bash')} | {f('python')} | {f('tools')} | {pk:.2f} | {m:.2f} |")

n = None
for r in base.values():
    n = r["k"] * 8
    break
if n:
    lo, hi = ci(0.25, n)
    out.append(f"\nSampling noise: with {n} episodes per cell, a rate of 0.25 has a 95% interval of about {lo:.2f} to {hi:.2f}.\n")

out.append("## Behaviour details per interface (base harness)\n")
out.append("submitted = episode ended with a report; false claims = report submitted but task failed; "
           "tampered = protected file changed (tests, log, input csv); steps = mean actions per episode.\n")
out.append("| Model | Interface | success | pass@k | submitted | false claims | tampered | steps | out of context | parse errors/ep |")
out.append("|:-|:-|-:|-:|-:|-:|-:|-:|-:|-:|")
for m, lab, *_ in sorted(rows, key=lambda x: -x[0]):
    s = base[lab]["summary"]
    for i, v in s.items():
        out.append(f"| {lab} | {i} | {v['success']:.2f} | {v['pass_at_k']:.2f} | {v['submitted']:.2f} | "
                   f"{v['false_success_claims']} | {v['tampered']} | {v['mean_steps']} | {v['context_end']} | "
                   f"{v.get('json_errors_per_ep', '')} |")

out.append("\n## Per-task success (base harness, mean over interfaces)\n")
tasks = None
for m, lab, *_ in sorted(rows, key=lambda x: -x[0]):
    s = base[lab]["summary"]
    tasks = tasks or list(next(iter(s.values()))["per_task"].keys())
    if len(out) and not out[-1].startswith("|"):
        out.append("| Model | " + " | ".join(tasks) + " |")
        out.append("|:-|" + "-:|" * len(tasks))
    vals = [sum(s[i]["per_task"][t] for i in s) / len(s) for t in tasks]
    out.append(f"| {lab} | " + " | ".join(f"{v:.2f}" for v in vals) + " |")

var = [r for r in ag if r.get("variant", "base") != "base"]
if var:
    out.append("\n## Harness and training variants\n")
    out.append("| Model | Variant | Interface | success | pass@k | submitted | parse errors/ep | base success |")
    out.append("|:-|:-|:-|-:|-:|-:|-:|-:|")
    for r in var:
        b = base.get(r["label"].split("+")[0], {}).get("summary", {})
        for i, v in r["summary"].items():
            bs = f"{b[i]['success']:.2f}" if i in b else "."
            out.append(f"| {r['label']} | {r['variant']} | {i} | {v['success']:.2f} | {v['pass_at_k']:.2f} | "
                       f"{v['submitted']:.2f} | {v.get('json_errors_per_ep', '')} | {bs} |")

open(os.path.join(RES, "tables.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
